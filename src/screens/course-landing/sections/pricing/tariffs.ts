import { COLOR, GAP, placePricing, type Tariff, type TicketRow } from "./layout";

/**
 * Содержимое билетов — строками сверху вниз. Переносы подобраны под Inter 17 и колонку 245:
 * строка текста — не шире 245, строка пункта списка — не шире 219 (маркер занимает 1.5em),
 * делится по смыслу. Координат здесь нет: их считает placePricing.
 */

const BROWN = COLOR.brown;
const INK = COLOR.ink;

const number = (fig: string, text: string): TicketRow => ({
  kind: "number",
  fig,
  text,
  gap: GAP.number,
});

/** Абзац описания над линией отрыва. */
const description = (
  fig: string,
  lines: readonly string[],
  gap: number = GAP.paragraph,
): TicketRow => ({ kind: "text", fig, lines, weight: 400, color: BROWN, gap });

const tear = (): TicketRow => ({ kind: "tear", gap: GAP.tear });

const title = (fig: string, text: string): TicketRow => ({
  kind: "title",
  fig,
  text,
  gap: GAP.title,
});

/** Полужирная строка: подзаголовок списка (отступ до списка) или сроки (gap — как у группы). */
const subhead = (fig: string, lines: readonly string[], gap: number = GAP.subhead): TicketRow => ({
  kind: "text",
  fig,
  lines,
  weight: 600,
  color: INK,
  gap,
});

/** Светлый текст без маркеров — на месте списка. */
const note = (fig: string, lines: readonly string[]): TicketRow => ({
  kind: "text",
  fig,
  lines,
  weight: 300,
  color: INK,
  gap: GAP.group,
});

const list = (fig: string, items: readonly (readonly string[])[]): TicketRow => ({
  kind: "list",
  fig,
  items,
  gap: GAP.group,
});

