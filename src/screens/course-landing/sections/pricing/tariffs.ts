import { COLOR, GAP, placePricing, type Tariff, type TicketRow } from "./layout";

/**
 * Содержимое билетов — строками сверху вниз, как в кассовом чеке: шапка по центру (название
 * и описание тарифа), под линией отрыва — сведения, состав по разделам и цены от левого поля,
 * кнопка по центру. Переносы подобраны под Inter 17 и колонку 326: строка заполняется до края
 * и переносится, только когда слово не помещается (предлог или союз в конце строки не остаётся).
 * Координат здесь нет: их считает placePricing.
 */

const BROWN = COLOR.brown;
const INK = COLOR.ink;

/** Название тарифа — как название магазина в шапке чека. */
const title = (fig: string, text: string): TicketRow => ({
  kind: "title",
  fig,
  text,
  gap: GAP.title,
});

/** Абзац описания в шапке, по центру. */
const description = (
  fig: string,
  lines: readonly string[],
  gap: number = GAP.paragraph,
): TicketRow => ({ kind: "text", fig, lines, weight: 400, color: BROWN, gap });

const tear = (): TicketRow => ({ kind: "tear", gap: GAP.tear });

/** Сведения о тарифе: строки «что: значение» от левого поля. */
const details = (lines: readonly string[]): TicketRow => ({
  kind: "text",
  lines,
  weight: 400,
  color: INK,
  align: "left",
  gap: GAP.section,
});

const divider = (line: "dashed" | "solid" = "dashed", gap: number = GAP.section): TicketRow => ({
  kind: "divider",
  line,
  gap,
});

/** Полужирная строка — подзаголовок раздела. */
const subhead = (fig: string, lines: readonly string[]): TicketRow => ({
  kind: "text",
  fig,
  lines,
  weight: 600,
  color: INK,
  align: "left",
  gap: GAP.subhead,
});

/** Светлый текст на месте списка. */
const note = (fig: string, lines: readonly string[]): TicketRow => ({
  kind: "text",
  fig,
  lines,
  weight: 300,
  color: INK,
  align: "left",
  gap: GAP.section,
});

const list = (fig: string, items: readonly (readonly string[])[]): TicketRow => ({
  kind: "list",
  fig,
  items,
  gap: GAP.section,
});

/** Цены, как итог чека: обычная цена, сплошная линия, итог крупно. */
const prices = (
  old: { fig: string; value: string },
  total: { fig: string; value: string },
  spoken: string,
): TicketRow[] => [
  { kind: "pair", ...old, label: "Обычная цена", role: "old", gap: GAP.pair },
  divider("solid", GAP.pair),
  { kind: "pair", ...total, label: "ИТОГО", role: "total", spoken, gap: GAP.section },
];

const button = (fig: string, label: string): TicketRow => ({
  kind: "button",
  fig,
  label,
  gap: GAP.bottom,
});

